    public enum Category { FARMER, CHASSEUR, BUCHERON, MINEUR }

    public record MissionTarget(Material material, EntityType entityType, int required) {
        public static MissionTarget material(Material mat, int req) { return new MissionTarget(mat, null, req); }
        public static MissionTarget mob(EntityType type, int req)   { return new MissionTarget(null, type, req); }
        public boolean isMob() { return entityType != null; }
    }

    // Helpers statiques courts
    private static MissionTarget mat(Material m, int req) { return MissionTarget.material(m, req); }
    private static MissionTarget mob(EntityType e, int req){ return MissionTarget.mob(e, req); }

    private final Category      category;
    private final String        name;
    private final String        description;
    private final MissionTarget target;
    private final double        isLevelReward;

    IslandMission(Category category, String name, String description,
                  MissionTarget target, double isLevelReward) {
        this.category      = category;
        this.name          = name;
        this.description   = description;
        this.target        = target;
        this.isLevelReward = isLevelReward;
    }

    public Category      getCategory()      { return category; }
    public String        getName()          { return name; }
    public String        getDescription()   { return description; }
    public MissionTarget getTarget()        { return target; }
    public double        getIsLevelReward() { return isLevelReward; }
